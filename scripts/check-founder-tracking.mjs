import assert from 'node:assert/strict';
import ts from 'typescript';
import { readFile } from 'node:fs/promises';
const load = async file => {
  const compiled = ts.transpileModule(await readFile(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
  return import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
};
const { filterTrackedUsers, hasCreatedResource, hasResourceData, isRecentlyActive, trackedUsersCsv } = await load('src/lib/founderTracking.ts');
const newUser = { id: 'new', name: 'Neemias Silva', email: 'neemias@example.test', plan: 'free', billing_status: 'none', created_at: new Date().toISOString(), confirmed_at: null, last_sign_in_at: null, last_seen_at: null, ideas: 0, projects: 0, solutions: 0, followup_status: 'new', follow_up_at: null };
const active = { ...newUser, id: 'active', name: 'José, "Silva"', email: 'jose@example.test', confirmed_at: new Date().toISOString(), last_sign_in_at: new Date().toISOString(), last_seen_at: new Date().toISOString(), projects: 2 };
const unknown = { ...newUser, id: 'unknown', ideas: null, projects: null, solutions: null };
assert.equal(filterTrackedUsers([newUser], 'neemias silva', 'all').length, 1);
assert.equal(filterTrackedUsers([active], 'jose', 'all').length, 1);
assert.equal(filterTrackedUsers([newUser, active], '@example.test', 'all').length, 2);
assert.deepEqual(filterTrackedUsers([newUser, active], '', 'no_login'), [newUser]);
assert.deepEqual(filterTrackedUsers([newUser, active], '', 'unconfirmed'), [newUser]);
assert.deepEqual(filterTrackedUsers([newUser, active, unknown], '', 'not_started'), [newUser]);
assert.equal(hasCreatedResource(active), true);
assert.equal(hasCreatedResource(newUser), false);
assert.equal(hasResourceData(unknown), false);
assert.equal(isRecentlyActive(newUser, 7), false);
assert.equal(isRecentlyActive(active, 7), true);
assert.equal(filterTrackedUsers([{ ...active, last_seen_at: '2000-01-01T00:00:00Z' }], '', 'active').length, 0);
assert.equal(filterTrackedUsers([{ ...newUser, follow_up_at: '2000-01-01' }], '', 'followup').length, 1);
assert.equal(filterTrackedUsers([{ ...newUser, follow_up_at: '2000-01-01', followup_status: 'resolved' }], '', 'followup').length, 0);
assert.match(trackedUsersCsv([active]), /"José, ""Silva"""/);
assert.match(trackedUsersCsv([{ ...newUser, name: '=FORMULA()' }]), /"'=FORMULA\(\)"/);
const cache = await load('src/lib/memoryCache.ts');
let calls = 0;
const loader = async () => ++calls;
assert.equal(await cache.getOrLoadCachedValue('founder:test', 60000, loader), 1);
assert.equal(await cache.getOrLoadCachedValue('founder:test', 60000, loader), 1);
assert.equal(await cache.getOrLoadCachedValue('founder:test', 60000, loader, { forceRefresh: true }), 2);
